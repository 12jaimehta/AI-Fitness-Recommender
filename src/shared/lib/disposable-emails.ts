const FAKE_LOCAL = new Set(["test", "testing", "fake", "asdf", "qwerty", "noreply", "no-reply", "mailer-daemon"]);

export function normalizeEmail(value: string) {
  return value.trim().toLowerCase();
}

export function emailDomain(email: string) {
  const at = email.lastIndexOf("@");
  if (at < 0) return "";
  return email.slice(at + 1);
}

export function isDisposableEmail(email: string) {
  const normalized = normalizeEmail(email);
  const at = normalized.lastIndexOf("@");
  if (at <= 0) return true;
  const local = normalized.slice(0, at);
  const domain = normalized.slice(at + 1);
  if (!local || !domain || !domain.includes(".")) return true;

  const tld = domain.slice(domain.lastIndexOf(".") + 1);
  if (BLOCKED_TLDS.has(tld)) return true;

  if (FAKE_LOCAL.has(local) && (domain === "test.com" || BLOCKED_DOMAINS.has(domain))) return true;

  const labels = domain.split(".");
  for (let i = 0; i < labels.length - 1; i++) {
    if (BLOCKED_DOMAINS.has(labels.slice(i).join("."))) return true;
  }
  return false;
}

export function disposableEmailMessage() {
  return "Use a real email address. Temporary or throwaway inboxes are not allowed.";
}

export function maskEmail(email: string) {
  const normalized = normalizeEmail(email);
  const at = normalized.lastIndexOf("@");
  if (at < 1) return normalized;
  const local = normalized.slice(0, at);
  const domain = normalized.slice(at + 1);
  return `${local.slice(0, 1)}***@${domain}`;
}
